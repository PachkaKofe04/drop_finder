def rgba(hex_color: str, alpha: float) -> str:
    """'#f07a86', 0.3 -> 'rgba(240, 122, 134, 0.3)'."""
    red, green, blue = (int(hex_color[i:i + 2], 16) for i in (1, 3, 5))
    return f"rgba({red}, {green}, {blue}, {alpha})"


def short_card(card: str) -> str:
    """Короткая подпись карты для графиков: '2202 **** **** 4821 #a1b2c3' -> '•• 4821 #a1b2c3'.

    Полный номер остаётся в подсказке. Токены и внутренние ID без маски
    короче 12 знаков не меняются, длинные сокращаются до последних 6 знаков.
    Названия организаций («Работодатель 3», «Банк: ипотека») остаются как есть.
    """
    if "****" in card:
        return "•• " + card.rsplit("****", 1)[1].strip()
    if " " in card or len(card) <= 12:
        return card
    return "•• " + card[-6:]
